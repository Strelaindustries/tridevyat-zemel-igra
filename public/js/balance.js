// Шанс, что бот примет сделку: он берёт только выгодное, ровный обмен даёт ноль.
export function dealChance(get, give, atWar = false) {
  if (get <= 0) return 0;
  const p = give <= 0 ? 1 : clamp((get / give - 1) / 0.6, 0, 1);
  return atWar ? p / 2 : p;
}

