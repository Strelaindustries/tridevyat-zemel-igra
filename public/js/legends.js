const pick = (list, rand) => list[Math.floor(rand() * list.length)];

// Новая легенда не повторяет героя и знамение прошлой партии.
export function makeLegend(rand, players, last = null) {
  const legends = LEGENDS.filter(l => l.hero !== last?.hero);
  const omens = OMENS.filter(o => o.id !== last?.omen);
  const legend = pick(legends, rand), omen = pick(omens, rand);
  const closing = pick(CLOSINGS, rand);
  return {
    id: legend.id, hero: legend.hero, title: legend.title, gift: legend.gift, curse: legend.curse,
    omen: omen.id, omenName: omen.name, mods: omen.mods,
    lines: [
      OPENINGS[legend.hero], ...legend.story,
      `Особый дар: ${legend.gift.name}.`, `Особое проклятье: ${legend.curse.name}.`, omen.line, closing,
    ],
  };
}
